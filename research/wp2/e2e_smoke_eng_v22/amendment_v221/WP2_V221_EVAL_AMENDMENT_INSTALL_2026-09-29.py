def norm_sha(data: bytes) -> str:
    if b"\x00" not in data[:8192]:
        data = data.replace(b"\r\n", b"\n")
    return hashlib.sha256(data).hexdigest()


def json_sha(obj) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True).encode("utf-8")).hexdigest()


class Stop(Exception):
    pass


def run(*args: str, check: bool = True, env_pp: bool = False) -> subprocess.CompletedProcess:
    env = None
    if env_pp:
        import os
        env = dict(os.environ)
        env["PYTHONPATH"] = os.pathsep.join([str(ROOT / "src"), str(ROOT),
                                             env.get("PYTHONPATH", "")])
        env["PYTHONIOENCODING"] = "utf-8"
    r = subprocess.run(args, cwd=ROOT, capture_output=True, text=True, encoding="utf-8",
                       errors="replace", env=env)
    if check and r.returncode != 0:
        raise Stop(f"command failed ({r.returncode}): {' '.join(args)}\n"
                   f"{(r.stdout + r.stderr)[-3000:]}")
    return r


def git(*args: str, check: bool = True) -> str:
    return run("git", *args, check=check).stdout.strip()


# ------------------------------------------------------------------ pre-checks (read-only)
def precheck_repo() -> dict:
    if not (ROOT / "scripts/wp2_ctl.py").exists():
        raise Stop("run from the repository root")
    if git("rev-parse", "--abbrev-ref", "HEAD") != "main":
        raise Stop("branch is not main")
    run("git", "fetch", "-q", "origin", "main")
    head, origin = git("rev-parse", "HEAD"), git("rev-parse", "origin/main")
    if head != origin:
        raise Stop(f"HEAD != origin/main ({head[:12]} vs {origin[:12]})")
    if git("tag", "--list", TAG):
        raise Stop(f"tag {TAG} already exists locally")
    if git("ls-remote", "--tags", "origin", f"refs/tags/{TAG}"):
        raise Stop(f"tag {TAG} already exists on origin")
    return {"head_before": head}


def precheck_state() -> None:
    st = json.loads(STATE.read_text(encoding="utf-8"))
    stop = st.get("stop") or {}
    if st.get("plan") != "WP2_E2E_SMOKE_ENG_V22":
        raise Stop(f"unexpected plan {st.get('plan')}")
    if stop.get("token") != "EVAL_PLAN_FAIL" or stop.get("phase") != "P09_EVAL_PLAN":
        raise Stop(f"unexpected controller stop {stop}")
    for p in PASSED_BEFORE:
        if st["phases"].get(p, {}).get("status") != "PASS":
            raise Stop(f"{p} is not PASS")
    if st["phases"].get("P09_EVAL_PLAN", {}).get("status") != "RUNNING":
        raise Stop("P09 is not RUNNING")
    for p in ("P10_EVALUATE", "P11_SUMMARY", "P12_CLOSE"):
        if st["phases"].get(p, {}).get("status", "PENDING") not in ("PENDING",):
            raise Stop(f"{p} already started")


def precheck_generation() -> dict:
    freeze = json.loads((V22 / "smoke_v22_freeze.json").read_text(encoding="utf-8"))
    if freeze.get("freeze_sha256") != BASE_FREEZE_SHA:
        raise Stop("smoke freeze sha differs from the audited one")
    gen = json.loads((V22 / "generation_freeze_v22.json").read_text(encoding="utf-8"))
    if gen.get("generation_freeze_sha256") != GEN_FREEZE_SHA:
        raise Stop("generation freeze sha differs from the audited one")
    body = {k: v for k, v in gen.items() if k != "generation_freeze_sha256"}
    if json_sha(body) != GEN_FREEZE_SHA:
        raise Stop("generation freeze self-hash mismatch")
    if gen.get("n_episodes") != EXPECTED["n_episodes"]:
        raise Stop("generation freeze n_episodes != 62")
    for rel, e in gen["episodes"].items():
        p = V22 / rel
        if not p.exists() or norm_sha(p.read_bytes()) != e["episode_file_sha256"]:
            raise Stop(f"generation evidence changed: {rel}")
    ev = V22 / "evaluations"
    existing = [p for p in ev.rglob("*") if p.is_file()] if ev.exists() else []
    if existing:
        raise Stop(f"evaluation files already exist: {[str(p) for p in existing[:5]]}")
    applied, ident, groups = 0, set(), {}
    for sub in ("episodes", "variance"):
        for p in sorted((V22 / sub).rglob("episode.json")):
            r = json.loads(p.read_text(encoding="utf-8"))
            if r["status"] == "APPLIED":
                applied += 1
                ident.add((r["task_id"], r["diff_sha256"]))
    for t, s in ident:
        groups.setdefault(s, set()).add(t)
    cross = {s: sorted(ts) for s, ts in groups.items() if len(ts) > 1}
    if applied != EXPECTED["applied"] or len(ident) != EXPECTED["unique_identities"]:
        raise Stop(f"census differs: applied={applied} identities={len(ident)}")
    if cross != {NOOP_SHA: sorted(NOOP_TASKS)}:
        raise Stop(f"cross-task group differs: { {k[:12]: v for k, v in cross.items()} }")
    return {"applied": applied, "unique_identities": len(ident),
            "cross_task_identical_diff_groups": {NOOP_SHA: sorted(NOOP_TASKS)},
            "freeze": freeze}


def precheck_old_files(freeze: dict) -> None:
    for rel, e in FREEZE_AMENDED.items():
        if freeze["code_sha256"].get(rel) != e["old"]:
            raise Stop(f"frozen hash of {rel} differs from the audited freeze")
        p = ROOT / rel
        if not p.exists() or norm_sha(p.read_bytes()) != e["old"]:
            raise Stop(f"{rel} on disk is not the frozen v2.2 file (edited?)")
    for rel, e in KIT_ONLY.items():
        p = ROOT / rel
        if e["old"] is None:
            if p.exists():
                raise Stop(f"{rel} unexpectedly exists")
        elif not p.exists() or norm_sha(p.read_bytes()) != e["old"]:
            raise Stop(f"{rel} on disk is not the v2.2 kit file (edited?)")


# ------------------------------------------------------------------ install (rollback-able)
class Installer:
    def __init__(self) -> None:
        self.backups: dict[str, bytes | None] = {}

    def write(self, rel: str, data: bytes) -> None:
        p = ROOT / rel
        if rel not in self.backups:
            self.backups[rel] = p.read_bytes() if p.exists() else None
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)

    def rollback(self) -> None:
        for rel, old in self.backups.items():
            p = ROOT / rel
            if old is None:
                if p.exists():
                    p.unlink()
            else:
                p.write_bytes(old)
        if ARCHIVE_DIR.exists():
            shutil.rmtree(ARCHIVE_DIR, ignore_errors=True)


