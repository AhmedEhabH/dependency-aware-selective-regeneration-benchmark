def tracked_files() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout
    return [f for f in out.splitlines() if f.strip()]


def classify(path: str) -> tuple[str, str, str]:
    name = path.rsplit("/", 1)[-1]
    for pat, cls in CLASS_MAP.items():
        if (
            pat.startswith("docs/")
            and pat.endswith("*.md")
            and path.startswith("docs/")
            and name.startswith(pat[len("docs/"):-len("*.md")])
        ):
            return cls
        if pat in (path, name):
            return cls
    if any(path.startswith(p) for p in ("reports/", "research/", "exports/", "runs_dryrun/")):
        return ("D", "immutable", "frozen evidence / report / receipt")
    if path.startswith("selective_updates/records/"):
        return ("D", "immutable", "frozen record")
    if any(
        path.startswith(p)
        for p in ("benchmark_data/", "config/", "src/", "scripts/", "tests/", "controller/", "kaggle_upload/")
    ):
        return ("C", "mutable", "code/config/workflow")
    if path.startswith("research/semantic_audit/"):
        return ("D", "immutable", "frozen rater/audit artifact")
    return ("C", "mutable", "unclassified workflow")


def action_for(path: str, line_no: int, line: str, file_cls: str) -> tuple[str, str]:
    low = line.lower()
    # 00_CURRENT_RESEARCH_STATE.md is an append-only record: only its rendered
    # LIVE block (lines 13-112 region) is regenerated from docs/LIVE_STATUS.json.
    if path == "00_CURRENT_RESEARCH_STATE.md" and line_no > 112:
        return (
            "KEEP_INTERNAL_WORKFLOW",
            "append-only research-state record; only the rendered LIVE block is regenerated",
        )
    for pat, reason in REVIEW_ONLY_PATTERNS:
        if pat.lower() in low:
            return ("KEEP_" + ("IMMUTABLE_PROVENANCE" if file_cls == "D" else "INTERNAL_WORKFLOW"), reason)
    if file_cls == "D":
        return ("KEEP_IMMUTABLE_PROVENANCE", "frozen evidence / report")
    if file_cls == "C":
        return ("KEEP_INTERNAL_WORKFLOW", "internal workflow / governance / mission record")
    if file_cls == "B":
        # benchmark reproducibility: keep model/provider identity, drop orchestrator narrative
        if "brain" in low and "review" in low:
            return ("REWRITE_RESEARCHER_CENTRIC", "orchestration-as-authority phrasing in current-state doc")
        if "brain" in low:
            return ("REWRITE_RESEARCHER_CENTRIC", "orchestration-as-authority phrasing in current-state doc")
        return ("KEEP_BENCHMARK_IDENTITY", "benchmark model/provider/budget identity")
    # class A public academic
    if "brain" in low or ("chatgpt" in low and "review" in low):
        return ("REWRITE_RESEARCHER_CENTRIC", "orchestration-as-scientific-authority in research-facing prose")
    if "openai" in low or "anthropic" in low:
        return ("REMOVE_IRRELEVANT_ORCHESTRATION", "irrelevant assistant provenance")
    return ("KEEP_REQUIRED_DISCLOSURE", "AI-use disclosure / legitimate entity")


def render_md(rows: list[dict]) -> str:
    counts = Counter(r["action"] for r in rows)
    cls_counts = Counter(r["file_class"] for r in rows)
    lines = [
        "# DOCUMENTATION PROVENANCE CENSUS — M17 (2026-10-12)",
        "",
        f"Total candidate mention rows: **{len(rows)}**",
        "",
        "## Matches by action",
        "",
        "| Action | Count |",
        "|:---|:---|",
    ]
    for act, c in counts.most_common():
        lines.append(f"| {act} | {c} |")
    lines += ["", "## Matches by file class", "", "| Class | Count |", "|:---|:---|"]
    for cls, c in cls_counts.most_common():
        lines.append(f"| {cls} | {c} |")
    lines += [
        "",
        "## Detail (first 120 rows)",
        "",
        "| Path | Line | Term | File class | Action | Reason |",
        "|:---|:---|:---|:---|:---|:---|",
    ]
    for r in rows[:120]:
        term = r["matched_term"][:60].replace("|", "\\|")
        reason = r["reason"][:80].replace("|", "\\|")
        lines.append(f"| {r['path']} | {r['line']} | {term} | {r['file_class']} | {r['action']} | {reason} |")
    lines += ["", "Full detail: `DOCUMENTATION_PROVENANCE_CENSUS.csv`.", ""]
    return "\n".join(lines)


def main() -> None:
    files = tracked_files()
    text_files = [f for f in files if f.endswith((".md", ".tex", ".rst", ".txt")) or f == "docs/LIVE_STATUS.json"]
    rows: list[dict] = []
    seen_aggregate: set[str] = set()
    for f in text_files:
        p = ROOT / f
        try:
            text = subprocess.run(
                ["git", "show", f"HEAD:{f}"], cwd=ROOT,
                capture_output=True, text=True, encoding="utf-8", errors="replace",
            ).stdout
        except Exception:
            if not p.is_file():
                continue
            text = p.read_text(encoding="utf-8", errors="replace")
        if "\x00" in text:
            continue
        file_cls, mutable, authority = classify(f)
        lines = text.splitlines()
        hit = False
        for i, line in enumerate(lines, start=1):
            m = TERM_RE.search(line)
            if m:
                hit = True
                action, reason = action_for(f, i, line, file_cls)
                rows.append({
                    "path": f, "line": i, "matched_term": m.group(0),
                    "context_excerpt": line.strip()[:140],
                    "file_class": file_cls,
                    "current_or_historical": "current" if mutable.startswith("mutable") else "historical",
                    "benchmark_relevant": "yes" if file_cls == "B" else "no",
                    "immutable": "yes" if file_cls == "D" else "no",
                    "action": action, "reason": reason,
                })
        if hit and f in AGGREGATE_FILES:
            seen_aggregate.add(f)
    # Add per-file aggregate rows for append-only/internal mega-files.
    for f in sorted(AGGREGATE_FILES):
        if f in seen_aggregate:
            continue
        p = ROOT / f
        if not p.is_file():
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        if "\x00" in text:
            continue
        n = len([m for m in TERM_RE.finditer(text)])
        if n:
            rows.append({
                "path": f, "line": "*", "matched_term": "(aggregate)",
                "context_excerpt": f"{n} candidate matches in append-only/internal record",
                "file_class": "C", "current_or_historical": "historical",
                "benchmark_relevant": "no", "immutable": "yes",
                "action": "KEEP_INTERNAL_WORKFLOW",
                "reason": "append-only governance / historical log record",
            })

    with (OUT / "DOCUMENTATION_PROVENANCE_CENSUS.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=[
            "path", "line", "matched_term", "context_excerpt", "file_class",
            "current_or_historical", "benchmark_relevant", "immutable", "action", "reason",
        ])
        w.writeheader()
        w.writerows(rows)
    (OUT / "DOCUMENTATION_PROVENANCE_CENSUS.md").write_text(render_md(rows), encoding="utf-8")

    # DOCUMENT_CLASSIFICATION.csv
    class_rows = []
    for f in sorted(set(r["path"] for r in rows)):
        file_cls, mutable, authority = classify(f)
        class_rows.append({
            "path": f, "class": file_cls, "mutable": "yes" if mutable.startswith("mutable") else "no",
            "authority_status": authority,
            "reason": "classification from M17 census scan",
        })
    # Add the four rendered targets + JSON explicitly.
    for f in ["README.md", "START_HERE_CURRENT_2026-09-21b.md", "PROGRESS.md",
              "00_CURRENT_RESEARCH_STATE.md", "docs/LIVE_STATUS.json"]:
        if f not in {r["path"] for r in class_rows}:
            file_cls, mutable, authority = classify(f)
            class_rows.append({
                "path": f, "class": file_cls,
                "mutable": "yes" if mutable.startswith("mutable") else "no",
                "authority_status": authority,
                "reason": "current-facing rendered target / source",
            })
    with (OUT / "DOCUMENT_CLASSIFICATION.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["path", "class", "mutable", "authority_status", "reason"])
        w.writeheader()
        w.writerows(class_rows)

    # DOCUMENTATION_MUTATION_PLAN.csv (every REWRITE action must have scientific_semantics_change=FALSE)
    plan_rows = []
    for r in rows:
        if r["action"] in ("REWRITE_RESEARCHER_CENTRIC", "REMOVE_IRRELEVANT_ORCHESTRATION"):
            plan_rows.append({
                "path": r["path"], "line_or_section": r["line"],
                "old_concept": r["context_excerpt"],
                "planned_new_concept": "neutral researcher/protocol/evidence-centered wording",
                "reason": r["reason"],
                "scientific_semantics_change": "FALSE",
            })
    with (OUT / "DOCUMENTATION_MUTATION_PLAN.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=[
            "path", "line_or_section", "old_concept", "planned_new_concept",
            "reason", "scientific_semantics_change",
        ])
        w.writeheader()
        w.writerows(plan_rows)

    print(f"census_rows={len(rows)}")
    print(f"mutation_plan_rows={len(plan_rows)}")
    print(f"class_rows={len(class_rows)}")


if __name__ == "__main__":
    main()
