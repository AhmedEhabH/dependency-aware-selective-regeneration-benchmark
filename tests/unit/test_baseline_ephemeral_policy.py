def test_t1_copy_baseline_skips_ephemeral_residue(tmp_path):
    workspace = tmp_path / "ws"
    _copy_baseline(workspace)
    residue = [
        p for p in workspace.rglob("*")
        if "__pycache__" in str(p) or p.suffix in (".pyc", ".pyo", ".sqlite3")
    ]
    assert residue == [], f"ephemeral residue copied into workspace: {residue}"


# T2 — baseline equivalence with generated bytecode ----------------------


def _baseline_hashes() -> dict[str, str]:
    hashes: dict[str, str] = {}
    for p in _BASELINE_REPO.rglob("*"):
        if p.is_file():
            rel = str(p.relative_to(_BASELINE_REPO).as_posix())
            if _is_ephemeral_baseline_path(rel):
                continue
            hashes[rel] = hashlib.sha256(p.read_bytes()).hexdigest()
    return hashes


def _assert_workspace_matches_baseline(workspace: Path) -> None:
    for rel in _baseline_hashes():
        if rel.startswith("todo/tests/"):
            assert (workspace / rel).read_bytes() == (_BASELINE_REPO / rel).read_bytes(), (
                f"baseline test file changed in workspace: {rel}"
            )


def test_t2_bytecode_residue_does_not_break_source_equivalence(tmp_path):
    workspace = tmp_path / "ws_residue"
    shutil.copytree(str(_BASELINE_REPO), str(workspace), symlinks=False)

    residue_dir = workspace / "todo" / "tests" / "__pycache__"
    residue_dir.mkdir(parents=True, exist_ok=True)
    residue = residue_dir / "test_models.cpython-311.pyc"
    residue.write_bytes(b"\x61\x0d\x0d\x0a runtime regenerated bytecode \x00" * 4)

    baseline_pyc = _BASELINE_REPO / "todo" / "tests" / "__pycache__" / "test_models.cpython-311.pyc"
    if baseline_pyc.is_file():
        assert baseline_pyc.read_bytes() != residue.read_bytes()

    _assert_workspace_matches_baseline(workspace)


def test_t2_real_source_drift_still_fails(tmp_path):
    workspace = tmp_path / "ws_drift"
    shutil.copytree(str(_BASELINE_REPO), str(workspace), symlinks=False)

    drifted = workspace / "todo" / "tests" / "test_models.py"
    drifted.write_bytes(drifted.read_bytes() + b"\n# real drift\n")

    import pytest

    with pytest.raises(AssertionError):
        _assert_workspace_matches_baseline(workspace)
