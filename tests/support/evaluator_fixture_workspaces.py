_BASELINE_REPO = Path(__file__).resolve().parent.parent.parent / "benchmark_data" / "repositories" / "todo"

_EPHEMERAL_BASELINE_MARKERS: tuple[str, ...] = (
    "__pycache__",
    ".pytest_cache",
    ".coverage",
    "db.sqlite3",
    ".git",
)


def _is_ephemeral_baseline_path(rel: str) -> bool:
    """Runtime-only ephemeral paths never participate in baseline equivalence.

    Bytecode and cache artifacts are generated by the runtime (for example
    ``manage.py test`` recompiling test modules) and must not be compared,
    copied, or hashed as if they were scientific source.
    """
    rel = rel.replace("\\", "/")
    if rel.endswith(".pyc") or rel.endswith(".pyo"):
        return True
    return any(marker in rel for marker in _EPHEMERAL_BASELINE_MARKERS)


def _copy_baseline(destination: Path) -> None:
    if destination.exists():
        shutil.rmtree(destination)

    def _ignore_ephemeral(_dir: str, names: list[str]) -> set[str]:
        return {name for name in names if _is_ephemeral_baseline_path(name)}

    shutil.copytree(
        str(_BASELINE_REPO),
        str(destination),
        symlinks=False,
        ignore=_ignore_ephemeral,
    )


def _overwrite(workspace: Path, relative_path: str, content: str) -> None:
    target = workspace / relative_path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content)


def _run_required_migration(workspace: Path) -> None:
    result = run_post_generation_command(
        workspace,
        (sys.executable, "manage.py", "makemigrations", "todo", "--noinput"),
        require_new_migration=True,
        timeout=180,
    )
    if not result.passed:
        raise RuntimeError(f"makemigrations failed: {result.stderr or result.stdout}")


def _apply_single_replacement(
    sources: dict[str, str], path: str, old: str, new: str
) -> dict[str, str]:
    content = sources[path]
    count = content.count(old)
    assert count == 1, f"Expected 1 occurrence of old string in {path}, found {count}"
    result = dict(sources)
    result[path] = content.replace(old, new, 1)
    return result


